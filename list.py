#append() method is used to add an element at the end of the list.
numbers =[1,2,3,4,5]
numbers.append(6)
print(numbers)


#extend() method is used to add multiple elements at the end of the list.
numbers = [1, 2, 3, 4, 5]
numbers.extend([6, 7, 8])
print(numbers)

numbers = [1, 2, 3, 4, 5]
numbers.insert(0, 10) #insert() method is used to add an element at a specific index in the list.
print(numbers)